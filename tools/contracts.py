#!/usr/bin/env python3
"""The HTTP contract of the local API and the review API, kept honest by machine.

  tools/contracts.py            rewrite packages/contracts/openapi.yaml from the Go routes
  tools/contracts.py --check    fail if the file is out of date, or if the web client calls a route that does not exist

The routes are read from the mux registrations in services/api (the single source of truth for what exists). The
file lists every path and method with its handler and which listener serves it. It does not yet describe request
and response bodies; the check below is about routes only, and says so in the file.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "packages" / "contracts" / "openapi.yaml"
SOURCES = [
    ("owner", ROOT / "services/api/internal/server/server.go"),
    ("review", ROOT / "services/api/internal/review/review.go"),
]
ROUTE = re.compile(r'mux\.Handle(?:Func)?\("([A-Z]+) (/[^"]*)"(?:,\s*([A-Za-z_.()]+))?')


def routes():
    found = []
    for listener, path in SOURCES:
        for m in ROUTE.finditer(path.read_text()):
            method, url, handler = m.group(1), m.group(2), (m.group(3) or "inline").strip("()")
            found.append((url, method.lower(), listener, handler))
    return sorted(set(found))


def render(rs):
    lines = [
        "# Generated by tools/contracts.py from the route registrations in services/api. Do not edit by hand.",
        "# Scope: paths, methods and which listener serves them. Request and response bodies are not described yet.",
        "openapi: 3.0.3",
        "info:",
        "  title: Vesqira local and review API",
        "  version: 0.2.0",
        "  description: The owner API listens on loopback only. The review API serves published previews to anyone holding a link.",
        "paths:",
    ]
    by_path = {}
    for url, method, listener, handler in rs:
        by_path.setdefault(url, []).append((method, listener, handler))
    for url in sorted(by_path):
        lines.append(f"  {url}:")
        params = re.findall(r"\{(\w+)\}", url)
        if params:
            lines.append("    parameters:")
            for p in params:
                lines.append(f"      - {{name: {p}, in: path, required: true, schema: {{type: string}}}}")
        for method, listener, handler in sorted(by_path[url]):
            lines.append(f"    {method}:")
            lines.append(f"      operationId: {listener}_{handler.replace('.', '_')}_{method}_{re.sub(r'[^A-Za-z0-9]+', '_', url).strip('_')}")
            lines.append(f"      x-listener: {listener}")
            lines.append("      responses: {'200': {description: ok}}")
    return "\n".join(lines) + "\n"


def client_calls():
    """Every /api or /review-api path the web client mentions, with template placeholders normalised."""
    out = set()
    for f in (ROOT / "apps/web/src/api").glob("*.ts"):
        if f.name.endswith(".test.ts"):
            continue
        text = f.read_text()
        for m in re.finditer(r"""[`"'](/(?:api|review-api)/[^`"'?]*)""", text):
            url = re.sub(r"\$\{[^}]*\}", "{}", m.group(1))
            url = re.sub(r"\$\{.*$", "", url)            # a template that goes on past the path (a query or suffix)
            url = re.sub(r"\.reg$", ".reg", url)
            out.add((f.name, url))
    return sorted(out)


def matches(call, spec_paths):
    parts = call.strip("/").split("/")
    for p in spec_paths:
        sp = p.strip("/").split("/")
        if len(sp) == len(parts) and all(a == b or a.startswith("{") for a, b in zip(sp, parts)):
            return True
    return False


def main():
    rs = routes()
    text = render(rs)
    if "--check" not in sys.argv:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(rs)} operations)")
        return 0
    errors = []
    if not OUT.exists() or OUT.read_text() != text:
        errors.append("packages/contracts/openapi.yaml is out of date: run tools/contracts.py")
    spec_paths = {u for u, *_ in rs}
    for fname, url in client_calls():
        # a path cut short at an unfinished template (e.g. `/api/hosts/${id}/list${query}`) must still be a prefix of a route
        if not matches(url, spec_paths) and not any(re.sub(r"\{\w+\}", "{}", sp).startswith(url) for sp in spec_paths):
            errors.append(f"apps/web/src/api/{fname} calls {url}, which no route serves")
    for e in errors:
        print("contracts:", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
